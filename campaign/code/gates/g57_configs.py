def complete_inputs(tmp: Path, cfgs: list) -> dict:
    """A constructed complete input record (synthetic values, never real results)."""
    s2 = tmp / 's2-synthetic.json'
    s2.write_text(json.dumps({'stage': 'S2', 'split': 'validation', 'form_choice': {'form': 'BF'},
                              'best': {'best': 'F011'}}))
    keys = {C.model_key(c) for c in cfgs if C.model_key(c)}
    keys |= {'lab|-|F011|BF|Q', 'lab|GR|F111|BF|Q', 'lab|BE|F111|BF|B'}
    pc = tmp / 'param-counts-synthetic.json'
    pc.write_text(json.dumps({'kind': 'cbl1016-param-counts', 'counts': {k: 1 for k in sorted(keys)}}))
    rec = json.loads((FORK / 'gen' / 'inputs.json').read_text())
    rec.update(headline='H2', claim_domain={'base': 'a', 'band_rule': None, 'c3r': False, 'c3r_level': None},
               s4_option='B', s2_record=str(s2), init_tensors={'root': '/kai-data/cbl1016/init', 'platform': 'gpu'},
               smoke_init_tensors={'root': '/kai-data/cbl1016/init-smoke', 'platform': 'gpu'}, bench_epochs=100,
               param_counts=str(pc))
    p = tmp / 'inputs-synthetic.json'
    p.write_text(json.dumps(rec, indent=1))
    return I.load(p)


